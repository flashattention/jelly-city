const JUNG_2 = new Set([9, 10, 11, 14, 15, 16, 19]); // ㅘ ㅙ ㅚ ㅝ ㅞ ㅟ ㅢ
const JONG_2 = new Set([3, 5, 6, 9, 10, 11, 12, 13, 14, 15, 18]); // ㄳ ㄵ ㄶ ㄺ ㄻ ㄼ ㄽ ㄾ ㄿ ㅀ ㅄ
export function strokesOf(ch) {
  const c = ch.charCodeAt(0) - 0xac00;
  if (c < 0 || c > 11171) return 1;
  const jung = Math.floor((c % 588) / 28), jong = c % 28; // 초성은 늘 1타 (쌍자음은 Shift + 1)
  return 1 + (JUNG_2.has(jung) ? 2 : 1) + (jong ? (JONG_2.has(jong) ? 2 : 1) : 0);
}
export const strokesIn = (s) => [...s].reduce((a, ch) => a + strokesOf(ch), 0);
// 맞게 친 타수: 같은 자리의 글자가 같으면 그 글자 타수만큼
export function correctStrokes(typed, target) { let n = 0; const a = [...typed], b = [...target]; for (let i = 0; i < Math.min(a.length, b.length); i++) if (a[i] === b[i]) n += strokesOf(b[i]); return n; }
export function rng(seed) { let a = seed >>> 0; return () => { a |= 0; a = (a + 0x6d2b79f5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
// 씨앗으로 같은 문장 n개
export function pickSentences(seed, n) { const r = rng(seed), idx = [...SENTENCES.keys()]; for (let i = idx.length - 1; i > 0; i--) { const j = Math.floor(r() * (i + 1)); [idx[i], idx[j]] = [idx[j], idx[i]]; } return idx.slice(0, n).map((i) => SENTENCES[i]); }
